export function citySpot(name: string): { lat: number; lng: number; label: string } | null {
  const raw = name.trim().toLowerCase().replace(/\s+/g, " ");
  if (!raw) return null;
  const key = ALIAS[raw] || raw;
  const pair = SPOT[key];
  if (!pair) return null;
  const label = key.replace(/\b\w/g, (ch) => ch.toUpperCase());
  return { lat: pair[0], lng: pair[1], label };
}
